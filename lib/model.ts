const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The three multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(protocol: SnapshotProtocol, asOf: string, model: ModelConstants): { implied: number; growthPct: number; growthMult: number; maturityMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult = model.maturity_floor + (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const base = protocol.tvl_usd * categoryMultiple(protocol.category, model);
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult));
  return { implied, growthPct, growthMult, maturityMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

const EXCLUDED_CATEGORIES = new Set(['Bridge', 'Canonical Bridge', 'Cross Chain Bridge', 'Liquid Staking', 'Liquid Restaking', 'Restaked BTC', 'CEX']);

/** Apply the watchlist's product exclusions without its TVL floor; parentProtocol is unavailable. */
export function exclusionReasons(p: SnapshotProtocol): string[] {
  const reasons: string[] = [];
  if (EXCLUDED_CATEGORIES.has(p.category ?? '')) reasons.push(`Excluded category: ${p.category}`);
  if (VERSIONED.test(p.name)) reasons.push('Versioned product of another protocol');
  if (/\b(wrapped|staked|staking)\b/i.test(p.name)) reasons.push('Wrapped or staked asset product');
  if (/^(Binance|Coinbase|Bybit|Kraken|Bitget|OKX|Bitfinex|Gemini)/i.test(p.name)) reasons.push('Exchange-branded product');
  return reasons;
}

/** No token recorded, and no watchlist product exclusion; no TVL floor. */
export function isRankable(p: SnapshotProtocol): boolean {
  return isPreToken(p) && exclusionReasons(p).length === 0;
}

/** Products removed from the former ranked universe, with no rank, valuation or farm plan. */
export function excludedRows(snapshot: Snapshot): (LiveRow & { reasons: string[] })[] {
  return snapshot.protocols
    .filter(p => isPreToken(p) && p.category !== 'CEX' && !VERSIONED.test(p.name) && !isRankable(p))
    .sort((a, b) => b.tvl_usd - a.tvl_usd || a.slug.localeCompare(b.slug))
    .map(p => ({ slug: p.slug, name: p.name, category: p.category, chains: p.chains, tvl_usd: p.tvl_usd, mcap_usd: p.mcap_usd, change_7d: p.change_7d, reasons: exclusionReasons(p) }));
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** The headline sentence's figures: how many watchlist slugs, how many rows, how many live protocols. */
export interface BoardSummary {
  watchlist_size: number;
  board_size: number;
  early_size: number;
  live_size: number;
}

/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, model: ModelConstants = calibrate(snapshot)): BoardRow[] {
  const index = bySlug(snapshot.protocols);
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug, even one the snapshot no longer carries (it cannot, but the
  // board's coverage is the gate's row and is never gambled on a missing record).
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined && isRankable(p)) chosen.set(slug, p);
  }
  // Include ALL eligible strict pre-token records, above and below the floor, with no cap.
  // Missing token metadata is not proof of a future launch; products are shown separately.
  const early = snapshot.protocols
    .filter((p) => !chosen.has(p.slug) && isRankable(p))
    .sort((a, b) => b.tvl_usd - a.tvl_usd || (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0))
    ;
  for (const p of early) chosen.set(p.slug, p);

  const scored = [...chosen.values()].map((p) => {
    const { implied, growthPct, growthMult, maturityMult, age } = impliedValue(p, snapshot.as_of, model);
    return { p, implied, growthPct, growthMult, maturityMult, age };
  });
  scored.sort((a, b) => b.implied - a.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  return scored.map((s, i) => ({
    rank: i + 1,
    slug: s.p.slug,
    name: s.p.name,
    category: s.p.category,
    chains: s.p.chains,
    tvl_usd: s.p.tvl_usd,
    change_7d: s.p.change_7d,
    mcap_usd: s.p.mcap_usd,
    listed_at: s.p.listed_at,
    gecko_id: s.p.gecko_id,
    symbol: s.p.symbol,
    token_status: 'pre-token',
    age_days: s.age,
    implied_value_usd: s.implied,
    model: {
      base_multiple: categoryMultiple(s.p.category, model),
      growth_pct: s.growthPct,
      growth_multiplier: round4(s.growthMult),
      maturity_multiplier: round4(s.maturityMult),
      age_days: s.age,
    },
    farm_steps: farmSteps(s.p, s.age).map(stepText),
  }));
}

const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  let s = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (s.length > 600) s = `${s.slice(0, 596)}...`;
  if (s.length < 20) s = `${s} Hold the position and check the protocol's own page.`;
  return s;
}

/** The first chain a protocol names, or a neutral phrase. */
function chainOf(p: SnapshotProtocol): string {
  return p.chains.length > 0 ? p.chains[0]! : 'its main chain';
}

/** How much capital one farm position needs, from the protocol's own TVL. */
function capitalFor(p: SnapshotProtocol): number {
  if (p.tvl_usd >= 5_000_000_000) return 250;
  if (p.tvl_usd >= 1_000_000_000) return 150;
  if (p.tvl_usd >= 100_000_000) return 100;
  return 50;
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  if (age < 180) return 60;
  if (age < 365) return 45;
  return 30;
}

/** The category's one action, in the words a farmer can follow. */
function actionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Supply $${capital} of USDC to ${name} on ${chain} and keep the position open.`;
  if (c.includes('curator') || c.includes('allocator') || c.includes('yield')) return `If publicly accessible, allocate up to $${capital} to a documented ${name} vault on ${chain}; verify the curator, underlying assets, fees and redemption queue before depositing.`;
  if (c.includes('dex') || c.includes('leveraged farm')) return `If supported, add up to $${capital} total to a liquid pair on ${name} on ${chain}; inspect price range, pool depth and impermanent loss, using no leverage.`;
  if (c.includes('bridge')) return `Bridge $${capital} of USDC to ${chain} through ${name} and use the bridged funds in its app.`;
  if (c.includes('staking') || c.includes('restak')) return `Stake $${capital} of the chain's staking asset through ${name} and keep the receipt.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Deposit $${capital} of USDC as margin on ${name} and open one small hedge.`;
  if (c.includes('prediction')) return `Fund $${capital} and place one market position on ${name}.`;
  if (c.includes('curator') || c.includes('allocator')) return `Deposit $${capital} into a ${name} vault on ${chain} and keep the shares.`;
  if (c.includes('stable')) return `Mint or deposit $${capital} of the stable asset through ${name} on ${chain}.`;
  if (c.includes('rwa')) return `Mint $${capital} of the protocol's yield asset on ${chain} and hold it.`;
  if (c.includes('insurance')) return `Buy $${capital} of cover from ${name} on ${chain} and keep the policy.`;
  return `Read ${name}'s ${p.category ?? 'protocol'} documentation on ${chain}. If a supported public interaction exists, test its minimum size, capped at $${capital}; otherwise keep this as a research-only candidate.`;
}

function reviewFor(p: SnapshotProtocol): string {
  const c = (p.category ?? '').toLowerCase();
  if (/lend|cdp|collateral/.test(c)) return 'check utilization, supply APY and collateral thresholds; avoid borrowing merely for points.';
  if (/dex|liquidity/.test(c)) return 'check whether liquidity is in range and compare fees earned with impermanent loss.';
  if (/bridge/.test(c)) return 'verify final settlement on the destination chain and test the supported return route.';
  if (/stak/.test(c)) return 'check validator concentration, receipt-token discount and the unstaking queue.';
  if (/perpetual|derivative|option|prediction/.test(c)) return 'check funding, margin or settlement date; cap maximum loss and close unnecessary exposure.';
  if (/rwa/.test(c)) return 'check eligibility, issuer attestations and redemption restrictions.';
  return 'check underlying exposures, share price, fees and withdrawal liquidity.';
}

/**
 * A protocol's farm plan: six steps, each an action with a cost and a time. The plan is derived from
 * the protocol's own record (category, chains, TVL, age), never from a hand-written list of names.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const action = actionFor(p, capital, chain);
  return [
    {
      text: `Verify ${p.name}'s official app and documentation independently. Confirm supported assets on ${chain}, access restrictions and whether a public deposit route or rewards program actually exists. Skip if unavailable.`,
      cost: '$0; do not fund before verification',
      time: '5 minutes',
    },
    {
      text: action,
      cost: `up to $${capital} at-risk capital; planning allowance $1–$15 gas plus fees, get an actual quote`,
      time: '15 minutes to set up',
    },
    {
      text: `Review the ${p.category ?? 'protocol'} position weekly: ${reviewFor(p)} Record balances and transaction receipts; do not churn transactions solely to seek rewards.`,
      cost: '$0 to inspect; any optional transaction needs a fresh fee quote',
      time: '10 minutes a week',
    },
    {
      text: `Use a ${hold}-day review window, exiting sooner if risk changes. Listing age is not proof of operating history or reward eligibility. Check withdrawal queues and principal loss before extending.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Check ${p.name}'s official announcements for an explicitly documented rewards program. This snapshot confirms neither points nor an airdrop; proceed only if the activity itself is worthwhile.`,
      cost: '$0 to inspect; claim gas only if a legitimate program is confirmed',
      time: '10 minutes',
    },
    {
      text: `Test a small withdrawal or close the position using ${p.name}'s verified app. Revoke unused approvals and record net fees, slippage and returned capital. Respect any redemption delay.`,
      cost: 'budget $1–$15 for exit gas plus quoted slippage; actual fees vary by chain',
      time: '10–20 minutes, plus any documented withdrawal queue',
    },
  ];
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => (p.gecko_id !== null || p.symbol !== null) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}


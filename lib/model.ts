// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x category median(mcap_usd / tvl_usd) from priced snapshot peers
// Categories with fewer than 3 priced peers use the overall median, preventing singleton
// outliers from overwhelming TVL. Raw medians, counts and applied multiples are exposed.
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(base x growthMult x maturity))
//
// The constants are the house model's, stated in the dashboard and changeable in the model sandbox. No
// protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  base_multiple: number;
  categories?: Record<string, { count: number; median: number; multiple: number; fallback: boolean }>;
  peer_count?: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.25,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'comps-2';

/** How many pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const MIN_CATEGORY_PEERS = 3;

export function median(values: number[]): number {
  const a = values.slice().sort((x, y) => x - y);
  if (!a.length) throw new SnapshotError('No priced live peers to calibrate');
  const i = Math.floor(a.length / 2);
  return a.length % 2 ? a[i]! : (a[i - 1]! + a[i]!) / 2;
}

export function calibrate(snapshot: Snapshot): ModelConstants {
  const peers = snapshot.protocols.filter((p) => p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0 && p.category !== 'CEX' && (p.symbol !== null || p.gecko_id !== null));
  const overall = median(peers.map((p) => p.mcap_usd! / p.tvl_usd));
  const categories: NonNullable<ModelConstants['categories']> = {};
  for (const category of [...new Set(snapshot.protocols.map((p) => p.category ?? 'Other'))].sort()) {
    const group = peers.filter((p) => (p.category ?? 'Other') === category);
    const raw = group.length ? median(group.map((p) => p.mcap_usd! / p.tvl_usd)) : overall;
    categories[category] = { count: group.length, median: raw, multiple: group.length >= MIN_CATEGORY_PEERS ? raw : overall, fallback: group.length < MIN_CATEGORY_PEERS };
  }
  return { ...MODEL, base_multiple: overall, peer_count: peers.length, categories };
}

export function categoryMultiple(category: string | null, model: ModelConstants): number {
  return model.categories?.[category ?? 'Other']?.multiple ?? model.base_multiple;
}

